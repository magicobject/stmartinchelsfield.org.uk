// `npm run import:calendar` — reads the parish's public Google Calendars and rewrites
// src/events.imported.mjs (the site's calendar data). Read-only against Google; the only
// file it changes is that one. Rules: src/calendar-import.config.mjs. Review the diff, run
// `npm test`, and open a pull request; nothing is live until that merges.
//
//   npm run import:calendar                      (range from the config)
//   npm run import:calendar -- --from=2026-09-01 --until=2027-06-30
//
// The calendar IDs come from .calendar-sources.local.json (git-ignored; see the .example
// file). Set CALENDAR_SOURCES_FILE to read them from somewhere else.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { importFeed } from './calendar-import.mjs';
import { IMPORT_RANGE, SOURCE_RULES } from '../src/calendar-import.config.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = Object.fromEntries(process.argv.slice(2).filter((a) => a.startsWith('--')).map((a) => a.slice(2).split('=')));
const from = args.from || IMPORT_RANGE.from;
const until = args.until || IMPORT_RANGE.until;
for (const d of [from, until]) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(d)) throw new Error(`dates must be YYYY-MM-DD, got "${d}"`);
}

const sourcesFile = process.env.CALENDAR_SOURCES_FILE || join(root, '.calendar-sources.local.json');
if (!existsSync(sourcesFile)) {
  throw new Error(`No calendar IDs found at ${sourcesFile}. Copy .calendar-sources.example.json to .calendar-sources.local.json and fill in the IDs.`);
}
const ids = JSON.parse(readFileSync(sourcesFile, 'utf8'));

const all = [];
const seen = new Set();
const summary = [];
for (const name of Object.keys(SOURCE_RULES)) {
  const id = ids[name];
  if (!id) throw new Error(`${sourcesFile} has no ID for "${name}"`);
  const url = `https://calendar.google.com/calendar/ical/${encodeURIComponent(id)}/public/basic.ics`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${name}: Google returned ${res.status} (is the calendar still public?)`);
  const { events, left } = importFeed(name, await res.text(), { from, until });
  let added = 0;
  for (const ev of events) {
    const key = `${ev.date}|${ev.time}|${ev.title}`;
    if (seen.has(key)) continue; // the same event on two calendars
    seen.add(key);
    all.push(ev);
    added += 1;
  }
  summary.push(`${name}: ${added} events kept; left out ${Object.entries(left).map(([why, n]) => `${n} ${why}`).join(', ') || 'none'}`);
}
all.sort((a, b) => (a.date === b.date ? a.time.localeCompare(b.time) : a.date.localeCompare(b.date)));

const q = JSON.stringify;
const lines = all.map((ev) => `  { date: ${q(ev.date)}, time: ${q(ev.time)}, title: ${q(ev.title)}, location: ${q(ev.location)}${ev.weekly ? ', weekly: true' : ''} },`);
const body = `// AUTO-GENERATED by \`npm run import:calendar\` — DO NOT EDIT BY HAND.
// Source: the parish's public Google Calendars (Church, Parish Events, Well Hill, and the
// Toddler Group from the Crosby Room calendar), filtered and tidied by the rules in
// src/calendar-import.config.mjs. Only dates, times, titles and places are kept.
// To add something that is not on the Google Calendar, use MANUAL_EVENTS in
// src/events.config.mjs. To change what the calendar says, change the Google Calendar and
// run the import again.
export const IMPORT_META = { importedAt: '${new Date().toISOString().slice(0, 10)}', from: '${from}', until: '${until}' };

export const IMPORTED_EVENTS = [
${lines.join('\n')}
];
`;
writeFileSync(join(root, 'src', 'events.imported.mjs'), body);
console.log(summary.join('\n'));
console.log(`\nWrote ${all.length} events (${from} to ${until}) to src/events.imported.mjs`);
